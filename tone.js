// Перекраска вещей в выбранный цвет — общая для слайдера (hero.js, шейдер) и картинок на страницах (site.js).
//
// Вещи сняты жёлтыми (#FFD400) с чёрным. Раньше жёлтый пиксель раскладывался на «белую» часть (канал B)
// и «жёлтую» (max(R,G) − B), а жёлтая просто заменялась выбранным цветом. Но канал R у жёлтой ткани почти
// упирается в 255: светлые и затенённые места отличаются в нём на ~20 %, объём живёт в канале G. Поэтому на
// тёмных и холодных цветах (синий, фиолетовый, розовый, белый) складки пропадали — вещь выглядела плоской
// заливкой (17.11.2026).
//
// Теперь переносится светлота: светлота пикселя в OKLab сравнивается со светлотой самого #FFD400 и с тем же
// местным контрастом ложится на выбранный цвет (L = Lцвета · (Lпикс / Lжёлт)^g, где g = GAIN · Lжёлт / Lцвета —
// перепад светлоты у складки тот же, что у жёлтой вещи). Насыщенность в тени падает вместе со светлотой
// (как у реальной ткани), в бликах цвет уходит к белому. Глубокие тени не проваливаются в чистый чёрный.
(() => {
  "use strict";
  const LREF = 0.8809;   // светлота OKLab цвета #FFD400
  const GAIN = 1.2;      // складки чуть глубже, чем в жёлтом исходнике: мягкий свет съёмки, на тёмных цветах они тише

  const lin = (v) => (v <= 0.04045 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4));
  const enc = (v) => { v = Math.min(1, Math.max(0, v)); return v <= 0.0031308 ? v * 12.92 : 1.055 * Math.pow(v, 1 / 2.4) - 0.055; };

  // sRGB 0..1 → OKLab [L, a, b]
  function oklab(r, g, b) {
    r = lin(r); g = lin(g); b = lin(b);
    const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
    const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
    const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
    return [0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s,
            1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s,
            0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s];
  }
  // OKLab → sRGB 0..1
  function srgb(L, A, B) {
    const l = L + 0.3963377774 * A + 0.2158037573 * B, m = L - 0.1055613458 * A - 0.0638541728 * B, s = L - 0.0894841775 * A - 1.2914855480 * B;
    const l3 = l * l * l, m3 = m * m * m, s3 = s * s * s;
    return [enc(4.0767416621 * l3 - 3.3077115913 * m3 + 0.2309699292 * s3),
            enc(-1.2684380046 * l3 + 2.6097574011 * m3 - 0.3413193965 * s3),
            enc(-0.0041960863 * l3 - 0.7034186147 * m3 + 1.7076147010 * s3)];
  }

  // Выбранный цвет: его OKLab и показатель g (одинаков для шейдера и для картинок).
  function target(hex) {
    const [L, A, B] = oklab(...[1, 3, 5].map((p) => parseInt(hex.slice(p, p + 2), 16) / 255));
    return { L, A, B, g: (GAIN * LREF) / L };
  }

  // Один жёлтый пиксель (sRGB 0..1) → выбранный цвет. Доля «жёлтости» (смешение с чёрным на краях полос
  // и т. п.) — снаружи, как и раньше: m = clamp(((R+G)/2 − B − 12/255) / (28/255)).
  function pixel(r, g, b, t) {
    const Lp = oklab(r, g, b)[0];
    const q = Math.max(Lp / LREF, 1e-4);
    const Lo = q <= 1 ? t.L * Math.pow(q, t.g) : t.L + (1 - t.L) * (1 - Math.pow(2 - Math.min(q, 2), t.g));
    const cs = Lo <= t.L ? Lo / t.L : (1 - Lo) / Math.max(1 - t.L, 1e-3);
    return srgb(Lo, t.A * cs, t.B * cs);
  }

  window.IZUM_TONE = { LREF, GAIN, target, pixel };
})();
